import { describe, expect, test } from "bun:test";

import { createMockAdapter } from "../server/adapter/mock.ts";
import { IFRAME_SANDBOX } from "../shared/duel.ts";

const png =
  "data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==";

describe("mock adapter", () => {
  test("returns recorded low and high pages with canned metrics", async () => {
    const adapter = createMockAdapter({ delayMs: { low: 0, high: 0 } });
    expect(adapter.mode).toBe("mock");
    const prompt = "pricing page for an AI API";
    const [low, high] = await Promise.all([
      adapter.generate({ prompt, effort: "low" }),
      adapter.generate({ prompt, effort: "high" }),
    ]);

    expect(low.source).toBe("mock");
    expect(high.source).toBe("mock");
    expect(low.effortValue).toBe(0.2);
    expect(high.effortValue).toBe(0.9);
    expect(low.latencyMs).toBe(840);
    expect(high.latencyMs).toBe(3180);
    expect(low.usage).toEqual({
      promptTokens: 420,
      completionTokens: 310,
      cachedPromptTokens: 0,
      estimated: false,
    });
    expect(high.usage.completionTokens).toBe(1640);
    expect(low.costUsd).toBe(0.000436);
    expect(high.costUsd).toBe(0.001766);
    expect(low.html).toContain(prompt);
    expect(high.html).toContain(prompt);
    expect(low.html).not.toBe(high.html);
    expect(low.html).toContain("Recorded short pass");
    expect(high.html).toContain("Recorded high-effort layout");
    expect(low.reasoning).toContain("Not an Inkling sample");
    expect(high.html.toLowerCase()).not.toContain("generated by inkling");
  });

  test("escapes the prompt and keeps an attached sketch inside the fixture", async () => {
    const adapter = createMockAdapter({ delayMs: { low: 0, high: 0 } });
    const result = await adapter.generate({
      prompt: `<script>alert("x")</script>`,
      effort: "low",
      imageDataUrl: png,
    });
    expect(result.html).not.toContain("<script>alert");
    expect(result.html).toContain("&lt;script&gt;");
    expect(result.html).toContain("Sketch attached");
    expect(result.html).toContain(png.slice("data:".length));
    expect(result.html).toContain("not sent to Tinker");
  });

  test("iframe sandbox allows scripts and refuses same-origin", () => {
    expect(IFRAME_SANDBOX).toBe("allow-scripts");
    expect(IFRAME_SANDBOX).not.toContain("allow-same-origin");
  });
});

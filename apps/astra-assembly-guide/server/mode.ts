import {
  LIVE_BANNER,
  MOCK_BANNER,
  REASONING_NOTE,
  type ModelKey,
} from "../shared/copy.ts";
import type { ModePayload } from "../shared/result.ts";
import { createMockAdapter } from "./adapter/mock.ts";
import { createOpenAIAdapter } from "./adapter/openai.ts";
import type { AssemblyAdapter } from "./adapter/types.ts";
import { modelIdFor, resolveMode } from "./env.ts";

export function selectAdapter(env: NodeJS.ProcessEnv = process.env): AssemblyAdapter {
  if (resolveMode(env) === "live") return createOpenAIAdapter(env);
  return createMockAdapter(env);
}

export function modePayload(env: NodeJS.ProcessEnv = process.env): ModePayload {
  const mode = resolveMode(env);
  const models: Record<ModelKey, string> = {
    astra: modelIdFor("astra", env),
    sol: modelIdFor("sol", env),
  };
  if (mode === "mock") {
    return {
      mode,
      banner: MOCK_BANNER,
      detail:
        "Both panes replay hand-authored fixtures with canned token counts. Latency is scaled from the recorded Standard timing, and USD is repriced with the selected tier's short-context rates. Nothing here was generated by gpt-6.2-astra or gpt-6.2-sol. A photo you upload is previewed and refused.",
      models,
      commands: liveCommands(),
      reasoningEffort: "low",
    };
  }
  return {
    mode,
    banner: LIVE_BANNER,
    detail: `Each Run calls the Responses API once per model with structured outputs, service_tier pinned on the request, and ${REASONING_NOTE}`,
    models,
    commands: liveCommands(),
    reasoningEffort: "low",
  };
}

function liveCommands(): string[] {
  return [
    "cd apps/astra-assembly-guide",
    "bun install && bun run dev",
    "OPENAI_API_KEY=… bun run dev",
    "OPENAI_MODEL_ASTRA and OPENAI_MODEL_SOL override the ids (default gpt-6.2-astra and gpt-6.2-sol)",
    "MOCK=1 forces the recorded fixtures even when a key is set",
  ];
}

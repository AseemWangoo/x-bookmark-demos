import { describe, expect, test } from "bun:test";

import { createMockAdapter, listFixtures, recordedPorts } from "../server/adapter/mock.ts";
import { MOCK_BANNER } from "../shared/port.ts";
import { createApp } from "../server/http.ts";
import { modePayload } from "../server/mode.ts";

describe("recorded fixtures", () => {
  test("three snippets each have a distinct low, medium, and high port", async () => {
    const fixtures = listFixtures();
    expect(fixtures.map((fixture) => fixture.id)).toEqual(["paddle-loop", "compound", "tip"]);
    const adapter = createMockAdapter();
    expect(adapter.mode).toBe("mock");

    for (const fixture of fixtures) {
      const ports = await Promise.all(
        (["low", "medium", "high"] as const).map((effort) =>
          adapter.port({ source: fixture.source, language: fixture.language, effort }),
        ),
      );
      const html = ports.map((port) => port.html);
      expect(new Set(html).size).toBe(3);
      ports.forEach((port, index) => {
        const effort = (["low", "medium", "high"] as const)[index]!;
        expect(port.source).toBe("mock");
        expect(port.effort).toBe(effort);
        expect(port.html).toContain(`data-effort="${effort}"`);
        expect(port.html.toLowerCase()).not.toContain("generated by gemini");
        expect(port.html.toLowerCase()).not.toContain("cursorbench");
        expect(port.usage.estimated).toBe(false);
        expect(port.usage.reasoningTokens).not.toBeNull();
        expect(port.usage.reasoningTokens!).toBeLessThanOrEqual(port.usage.outputTokens);
        expect(port.usage.cachedInputTokens).toBeLessThanOrEqual(port.usage.inputTokens);
      });
      expect(ports[0]!.latencyMs).toBeLessThan(ports[1]!.latencyMs);
      expect(ports[1]!.latencyMs).toBeLessThan(ports[2]!.latencyMs);
    }
  });

  test("stored fixture costs match the intro formula", () => {
    for (const row of recordedPorts()) {
      expect(row.costUsd).toBe(row.metaCostUsd);
    }
  });

  test("an unmatched paste stays labelled mock and estimated", async () => {
    const port = await createMockAdapter().port({
      source: "10 PRINT \"HI\"\n20 GOTO 10",
      effort: "high",
    });
    expect(port.source).toBe("mock");
    expect(port.usage.estimated).toBe(true);
    expect(port.html).toContain("data-mock-template=\"true\"");
    expect(port.html).toContain("Not a Gemini 4 Carbon port");
    expect(port.notes[0]).toContain("labelled estimate");
  });

  test("mode payload uses the mock banner and omits any key", () => {
    const payload = modePayload(createMockAdapter());
    expect(payload.banner).toBe(MOCK_BANNER);
    expect(payload.mode).toBe("mock");
    expect(JSON.stringify(payload)).not.toContain("AI_GATEWAY_API_KEY=");
    expect(payload.setup.join(" ")).toContain("AI_GATEWAY_API_KEY");
    expect(payload.setup.join(" ")).toContain("google/gemini-4-carbon");
  });

  test("http returns the recorded paddle port", async () => {
    const fixture = listFixtures()[0]!;
    const app = createApp(createMockAdapter());
    const response = await app.handle(
      new Request("http://port.local/api/port", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ source: fixture.source, language: fixture.language, effort: "high" }),
      }),
    );
    expect(response.status).toBe(200);
    const body = (await response.json()) as { html: string; source: string; costUsd: number; latencyMs: number };
    expect(body.source).toBe("mock");
    expect(body.latencyMs).toBe(6400);
    expect(body.costUsd).toBe(0.02268);
    expect(body.html).toContain('data-effort="high"');
  });
});

import { LIVE_BANNER, MOCK_BANNER } from "../shared/copy.ts";
import type { ModePayload, ProviderId } from "../shared/types.ts";
import { createMockAdapter } from "./adapter/mock.ts";
import { createLiveAdapter } from "./adapter/live.ts";
import type { ExtractAdapter } from "./adapter/types.ts";
import {
  baseUrlFor,
  defaultProvider,
  explicitProvider,
  isConfigured,
  keyPresent,
  modelFor,
  resolveMode,
  tokenhubRegion,
} from "./env.ts";

const LABELS: Record<ProviderId, string> = {
  tokenhub: "TokenHub",
  openrouter: "OpenRouter",
  custom: "Custom",
};

export function selectAdapter(env: NodeJS.ProcessEnv = process.env): ExtractAdapter {
  if (resolveMode(env) === "live") return createLiveAdapter(env);
  return createMockAdapter(env);
}

function commands(): string[] {
  return [
    "cd apps/hy4-flash-whiteboard-to-tasks",
    "bun install && bun run dev",
    "TOKENHUB_API_KEY=… bun run dev",
    "OPENROUTER_API_KEY=… HY4_FLASH_PROVIDER=openrouter bun run dev",
    "HY4_FLASH_BASE_URL=http://127.0.0.1:8000/v1 HY4_FLASH_PROVIDER=custom bun run dev",
    "MOCK=1 forces the recorded fixtures even when a key is set",
  ];
}

export function modePayload(env: NodeJS.ProcessEnv = process.env): ModePayload {
  const mode = resolveMode(env);
  const provider = mode === "live" ? defaultProvider(env) : null;
  const explicit = explicitProvider(env);
  const mismatch = explicit !== null && !isConfigured(explicit, env);
  const model = provider ? modelFor(provider, env) : "hy4-flash";
  let baseUrl: string | null = null;
  if (provider) {
    try {
      baseUrl = baseUrlFor(provider, env);
    } catch {
      baseUrl = null;
    }
  }
  const providers = (["tokenhub", "openrouter", "custom"] as const).map((id) => ({
    id,
    label: LABELS[id],
    model: safeModel(id, env),
    configured: isConfigured(id, env),
  }));
  if (mode === "mock") {
    return {
      mode,
      banner: MOCK_BANNER,
      detail: mockDetail(mismatch, explicit),
      provider: null,
      model,
      baseUrl: null,
      region: null,
      effortDefault: "no_think",
      providers,
      commands: commands(),
      keyPresent: keyPresent(env),
    };
  }
  return {
    mode,
    banner: LIVE_BANNER,
    detail: liveDetail(provider, model, baseUrl, mismatch, explicit),
    provider,
    model,
    baseUrl,
    region: provider === "tokenhub" ? tokenhubRegion(env) : null,
    effortDefault: "no_think",
    providers,
    commands: commands(),
    keyPresent: true,
  };
}

function safeModel(provider: ProviderId, env: NodeJS.ProcessEnv): string {
  try {
    return modelFor(provider, env);
  } catch {
    return "hy4-flash";
  }
}

function mockDetail(mismatch: boolean, explicit: ProviderId | null): string {
  const base =
    "Hand-authored sample fixtures with canned TTFT, tokens, and cost. Nothing here was generated by hy4-flash, and the boards are not Tencent assets. A photo or thread that is not one of the two samples is refused.";
  if (!mismatch || !explicit) return base;
  return `${base} HY4_FLASH_PROVIDER=${explicit} is set but that provider is not configured, so the desk stayed on samples.`;
}

function liveDetail(
  provider: ProviderId | null,
  model: string,
  baseUrl: string | null,
  mismatch: boolean,
  explicit: ProviderId | null,
): string {
  const host = baseUrl ?? "the provider default";
  const note = mismatch && explicit ? ` HY4_FLASH_PROVIDER=${explicit} is not configured, so the desk used ${provider}.` : "";
  return `One Chat Completions call per extract. Provider ${provider} · model ${model} · ${host}. Images go as image_url data URLs with detail high. Flash sends reasoning off (TokenHub no_think / thinking disabled, OpenRouter reasoning.enabled false, custom chat_template_kwargs).${note}`;
}
